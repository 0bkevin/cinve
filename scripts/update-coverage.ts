// Snapshots the cities each provider publishes into src/web/coverage.ts, so
// the landing page can list them without calling the cinemas on every visit.
// Run it when a cinema opens or closes a city:
//   npx tsx scripts/update-coverage.ts
import { writeFileSync } from 'node:fs';
import { today } from '../src/core.js';
import { CinemaService } from '../src/service.js';

// Cinex publishes city names in capitals; show every name in title case.
const titleCase = (name: string) => name.toLocaleLowerCase('es').replace(/(^|[\s-])(\p{L})/gu, (_, gap: string, letter: string) => gap + letter.toLocaleUpperCase('es'));

const service = new CinemaService();
const cities: Record<string, string[]> = {};
for (const provider of ['cinex', 'cinesunidos', 'cinepic'] as const) {
  const result = await service.query('cities', { provider });
  if (result.status !== 'available' || !result.items.length) throw new Error(`${provider}: ${result.status} ${result.warnings.join(' ')}`);
  cities[provider] = [...new Set(result.items.map(item => titleCase(String(item.name))))].sort((a, b) => a.localeCompare(b, 'es'));
}

writeFileSync('src/web/coverage.ts', `// Generated by scripts/update-coverage.ts from each provider's city list.
export const coverageDate = '${today()}';
export const coverage = ${JSON.stringify(cities, null, 2)} as const;
`);
console.log(cities);
